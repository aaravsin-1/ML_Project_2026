"""Compile a trained LightGBM model into dependency-free C++ (nested if/else per tree).

Same idea as Treelite/TL2cgen/lleaves. Used by scripts/benchmark_trained_model.py.
Needs only the LightGBM booster, no training data.
"""

from pathlib import Path


def tree_to_cpp(node: dict, depth: int = 1) -> str:
    pad = "    " * depth
    if "leaf_value" in node:
        return f"{pad}return {node['leaf_value']!r};\n"
    assert node["decision_type"] == "<=", node["decision_type"]
    f, thr = node["split_feature"], node["threshold"]
    # Features are never NaN here (the pipeline zero-fills), so missing-value routing is not needed
    return (f"{pad}if (static_cast<double>(x[{f}]) <= {thr!r}) {{\n"
            + tree_to_cpp(node["left_child"], depth + 1)
            + f"{pad}}} else {{\n"
            + tree_to_cpp(node["right_child"], depth + 1)
            + f"{pad}}}\n")


def generate_cpp(booster, num_iteration: int, path: Path) -> dict:
    dump = booster.dump_model(num_iteration=num_iteration)
    n_class = dump["num_class"]
    trees = dump["tree_info"]
    lines = ["// Auto-generated by scripts/benchmark_trained_model.py from a trained LightGBM model.",
             "#pragma once", "#include <cstddef>", "", "namespace btc_model {", "",
             f"constexpr int kNumFeatures = {dump['max_feature_idx'] + 1};",
             f"constexpr int kNumClass = {n_class};", ""]
    for i, t in enumerate(trees):
        lines.append(f"inline double tree_{i}(const float* x) {{")
        lines.append(tree_to_cpp(t["tree_structure"]).rstrip("\n"))
        lines.append("}")
    lines.append("")
    lines.append("// Raw (pre-softmax) scores; trees are interleaved by class as in LightGBM multiclass.")
    lines.append("inline void predict_raw(const float* x, double* out) {")
    for c in range(n_class):
        terms = " + ".join(f"tree_{i}(x)" for i in range(c, len(trees), n_class)) or "0.0"
        lines.append(f"    out[{c}] = {terms};")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace btc_model")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    leaves = sum(t["num_leaves"] for t in trees)
    return {"num_trees": len(trees), "num_class": n_class, "total_leaves": leaves,
            "num_features": dump["max_feature_idx"] + 1}
