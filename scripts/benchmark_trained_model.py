"""Benchmark the TRAINED LightGBM model compiled to native C++ (not the random-tree benchmark).

1. Trains the Experiment-A LightGBM (k = 20) on real BTC segment 0 and saves it.
2. Compiles the model to C++: every tree becomes nested if/else code (generated from
   LightGBM's JSON dump), the same idea as Treelite/TL2cgen/lleaves, with no dependencies.
3. Exports real test-set feature rows and LightGBM's own raw scores.
4. Builds cpp/src/trained_model_benchmark.cpp with g++ -O3 -march=native, which times
   single-row predictions and checks they match LightGBM to floating-point precision.
5. Times LightGBM's Python predict on single rows for comparison.

    python scripts/benchmark_trained_model.py
"""

import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import numpy as np
import pandas as pd

from src.config import ARTIFACTS_DIR
from src.experiments.common import btc_sessions, prepare_data
from src.models.tabular_trees import LightGBMLOB

GEN_DIR = ROOT / "cpp" / "generated"
OUT_DIR = ARTIFACTS_DIR / "cpp_trained_model"
N_ROWS = 20000


def tree_to_cpp(node: dict, depth: int = 1) -> str:
    pad = "    " * depth
    if "leaf_value" in node:
        return f"{pad}return {node['leaf_value']!r};\n"
    assert node["decision_type"] == "<=", node["decision_type"]
    f, thr = node["split_feature"], node["threshold"]
    # Features are never NaN here (the pipeline zero-fills), so missing-value routing is not needed
    return (f"{pad}if (static_cast<double>(x[{f}]) <= {thr!r}) {{\n"
            + tree_to_cpp(node["left_child"], depth + 1)
            + f"{pad}}} else {{\n"
            + tree_to_cpp(node["right_child"], depth + 1)
            + f"{pad}}}\n")


def generate_cpp(booster, num_iteration: int, path: Path) -> dict:
    dump = booster.dump_model(num_iteration=num_iteration)
    n_class = dump["num_class"]
    trees = dump["tree_info"]
    lines = ["// Auto-generated by scripts/benchmark_trained_model.py from a trained LightGBM model.",
             "#pragma once", "#include <cstddef>", "", "namespace btc_model {", "",
             f"constexpr int kNumFeatures = {dump['max_feature_idx'] + 1};",
             f"constexpr int kNumClass = {n_class};", ""]
    for i, t in enumerate(trees):
        lines.append(f"inline double tree_{i}(const float* x) {{")
        lines.append(tree_to_cpp(t["tree_structure"]).rstrip("\n"))
        lines.append("}")
    lines.append("")
    lines.append("// Raw (pre-softmax) scores; trees are interleaved by class as in LightGBM multiclass.")
    lines.append("inline void predict_raw(const float* x, double* out) {")
    for c in range(n_class):
        terms = " + ".join(f"tree_{i}(x)" for i in range(c, len(trees), n_class)) or "0.0"
        lines.append(f"    out[{c}] = {terms};")
    lines.append("}")
    lines.append("")
    lines.append("}  // namespace btc_model")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    leaves = sum(t["num_leaves"] for t in trees)
    return {"num_trees": len(trees), "num_class": n_class, "total_leaves": leaves,
            "num_features": dump["max_feature_idx"] + 1}


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    session = btc_sessions(4)[0]
    data = prepare_data(session)
    k = 20
    y, idx, X = data.labels(k), data.splits(k), data.tab_feat
    model = LightGBMLOB(num_leaves=63, max_depth=8, learning_rate=0.05, n_estimators=200, random_state=0)
    model.fit(X[idx["train"]], y[idx["train"]], X[idx["val"]], y[idx["val"]], early_stopping_rounds=15)
    booster = model.model.booster_
    best = model.model.best_iteration_ or booster.current_iteration()
    booster.save_model(str(OUT_DIR / "btc_lightgbm_segment0_k20.txt"), num_iteration=best)

    info = generate_cpp(booster, best, GEN_DIR / "btc_lightgbm_model.hpp")
    print(f"[+] generated C++ for {info}")

    rows = np.ascontiguousarray(X[idx["test"][:N_ROWS]], dtype=np.float32)
    raw = booster.predict(rows, num_iteration=best, raw_score=True).astype(np.float64)
    rows.tofile(OUT_DIR / "features.bin")
    raw.tofile(OUT_DIR / "lightgbm_raw_scores.bin")

    # Python single-row latency for comparison (raw booster, no sklearn wrapper)
    py_ns = []
    for i in range(2000):
        t0 = time.perf_counter_ns()
        booster.predict(rows[i:i + 1], num_iteration=best, raw_score=True)
        py_ns.append(time.perf_counter_ns() - t0)
    py_ns = np.array(py_ns)

    exe = ROOT / "cpp" / ("trained_model_benchmark.exe" if sys.platform == "win32" else "trained_model_benchmark")
    cxx = shutil.which("g++") or shutil.which("clang++")
    subprocess.run([cxx, "-std=c++20", "-O3", "-march=native", "-I", str(GEN_DIR),
                    str(ROOT / "cpp" / "src" / "trained_model_benchmark.cpp"), "-o", str(exe)], check=True)
    res = subprocess.run([str(exe), str(OUT_DIR / "features.bin"), str(OUT_DIR / "lightgbm_raw_scores.bin"),
                          str(len(rows))], capture_output=True, text=True, check=True)
    print(res.stdout)
    cpp = json.loads(res.stdout.strip().splitlines()[-1])

    result = {
        **info, "best_iteration": best, "rows": len(rows),
        "cpp_p50_ns": cpp["p50_ns"], "cpp_p99_ns": cpp["p99_ns"], "cpp_p999_ns": cpp["p999_ns"],
        "cpp_batch_ns_per_row": cpp["batch_ns_per_row"],
        "cpp_max_abs_diff_vs_lightgbm": cpp["max_abs_diff"], "cpp_argmax_agreement": cpp["argmax_agreement"],
        "python_lightgbm_p50_ns": float(np.percentile(py_ns, 50)),
        "python_lightgbm_p99_ns": float(np.percentile(py_ns, 99)),
    }
    pd.DataFrame([result]).to_csv(ARTIFACTS_DIR / "cpp_trained_model_benchmark.csv", index=False)
    print(pd.Series(result).to_string())


if __name__ == "__main__":
    main()
